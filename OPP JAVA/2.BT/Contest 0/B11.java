import java.util.Scanner;

public class B11 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        long n = sc.nextLong();
        System.out.println(n*2);
        System.out.println("");
        System.out.println((long)n*10);
        System.out.println("");
        System.out.println(n/2);
        System.out.println("");
        System.out.printf("%.3f",(double)n/2);

    }
 
}
